    /** 名詞按鈕（會議頁、說明頁用）；不在名詞表的詞原樣輸出 */
    public static function term($t, $cls = '')
    {
        $t = (string)$t;
        $terms = self::terms();
        if (!isset($terms[$t])) {
            return htmlspecialchars($t, ENT_QUOTES, 'UTF-8');
        }
        return sprintf('<button type="button" class="term %s" data-term="%s">%s</button>', htmlspecialchars($cls, ENT_QUOTES, 'UTF-8'), htmlspecialchars($t, ENT_QUOTES, 'UTF-8'), htmlspecialchars($t, ENT_QUOTES, 'UTF-8'));
    }

    /** 給前端的 JSON（名詞小視窗） */
    public static function json()
    {
        return json_encode(['terms' => self::terms(), 'more' => self::more()], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    }
